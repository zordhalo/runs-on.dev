// Generates lib/blog-posts.generated.js from content/blog/*.md: frontmatter
// plus the rendered HTML, baked into a committed module. Blog pages import
// the generated module — they never read the filesystem, which keeps
// prerendering hermetic (page-render workers do not share the build
// process's working directory).
//
// Run after writing or editing a post:
//   node scripts/generate-blog-content.mjs
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import matter from 'gray-matter';
import { marked } from 'marked';

const DIR = 'content/blog';

const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
// Optional media must be a root-relative path (file committed under
// public/blog-media/) or an absolute https URL.
const MEDIA_PATH = /^\/|https:\/\//;

function loadPosts() {
  if (!existsSync(DIR)) return [];
  const posts = [];
  for (const file of readdirSync(DIR)) {
    if (!file.endsWith('.md')) continue;
    const slug = file.replace(/\.md$/, '');
    const raw = readFileSync(`${DIR}/${file}`, 'utf8');
    const { data, content } = matter(raw);
    const d = data ?? {};
    for (const field of ['date', 'updated']) {
      if (d[field] instanceof Date) d[field] = d[field].toISOString().slice(0, 10);
    }
    // Optional media: warn-and-drop on malformed values rather than failing
    // the whole content build.
    for (const field of ['image', 'video']) {
      if (d[field] !== undefined && (typeof d[field] !== 'string' || !(d[field].startsWith('/') || d[field].startsWith('https://')))) {
        console.warn(`[${file}] ignoring malformed ${field}: must be a root-relative path or an https URL`);
        delete d[field];
      }
    }
    const rendered = withHeadingIds(marked.parse(content.trim(), { async: false, gfm: true }));
    posts.push({
      slug,
      title: d.title ?? '',
      description: d.description ?? '',
      date: d.date ?? '',
      updated: d.updated ?? null,
      author: d.author ?? '',
      category: d.category ?? '',
      tags: Array.isArray(d.tags) ? d.tags : [],
      status: d.status ?? 'published',
      image: d.image ?? null,
      video: d.video ?? null,
      html: rendered.html,
      headings: rendered.headings,
      // Raw markdown rides along for the copy-page menu and the .md twin;
      // frontmatter is deliberately excluded, the twin route rebuilds it
      // from the fields so there is one source of truth per field.
      markdown: content.trim(),
    });
  }
  return posts.sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : a.slug.localeCompare(b.slug)));
}

// Adds slug ids to h2/h3 and collects them for the "On this page" menu, so
// the TOC, the deep links, and the post HTML can never disagree.
function withHeadingIds(html) {
  const headings = [];
  const used = new Set();
  const slugify = (t) =>
    t.toLowerCase().replace(/&[a-z]+;/g, '').replace(/[^a-z0-9\s-]/g, '').trim().replace(/\s+/g, '-') || 'section';
  const out = html.replace(/<h([23])>([\s\S]*?)<\/h\1>/g, (m, lvl, inner) => {
    const text = inner.replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&#39;/g, "'").replace(/&quot;/g, '"').trim();
    let id = slugify(text);
    let n = 2;
    const base = id;
    while (used.has(id)) id = `${base}-${n++}`;
    used.add(id);
    headings.push({ id, text, level: Number(lvl) });
    return `<h${lvl} id="${id}">${inner}</h${lvl}>`;
  });
  return { html: out, headings };
}

const posts = loadPosts().filter((p) => p.title && p.date);

const out = `// Generated by scripts/generate-blog-content.mjs from content/blog/*.md.
// Regenerate after writing or editing a post; do not hand-edit.
export const BLOG_POSTS = ${JSON.stringify(posts, null, 2)};
`;
writeFileSync('lib/blog-posts.generated.js', out);
console.log(`wrote lib/blog-posts.generated.js: ${posts.length} posts (${posts.filter((p) => p.status === 'published').length} published)`);
